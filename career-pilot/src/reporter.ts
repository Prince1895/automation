import nodemailer from 'nodemailer';
import pool from './db.js';
import dotenv from 'dotenv';

dotenv.config();

export async function sendNightlyReport() {
    try {
        const result = await pool.query(`
            SELECT company_name, job_title, job_url, match_score, status
            FROM applications
            WHERE applied_at >= CURRENT_DATE
        `);

        const apps = result.rows;

        if (apps.length === 0) {
            console.log("No applications today. Skipping report.");
            return;
        }

        let reportTable = `
        <table border="1" style="border-collapse: collapse; width: 100%;">
            <tr style="background-color: #f2f2f2;">
                <th>Company</th>
                <th>Role</th>
                <th>Match %</th>
                <th>Status</th>
                <th>Link</th>
            </tr>
        `;

        apps.forEach(app => {
            reportTable += `
            <tr>
                <td>${app.company_name}</td>
                <td>${app.job_title}</td>
                <td>${app.match_score}%</td>
                <td>${app.status}</td>
                <td><a href="${app.job_url}">View Job</a></td>
            </tr>
            `;
        });
        reportTable += `</table>`;

        const emailHtml = `
            <h2>🚀 Career Pilot: Daily Executive Summary</h2>
            <p>Hello Prince, here is the report of the applications handled today:</p>
            ${reportTable}
            <br>
            <h3>⏭️ Next Steps:</h3>
            <ul>
                <li><strong>Check Drive:</strong> All tailored PDFs and Cover Letters have been uploaded to your Google Drive.</li>
                <li><strong>Monitor Email:</strong> I am actively monitoring your inbox for recruiter replies.</li>
                <li><strong>Prepare:</strong> Review the "Match Reasoning" in the logs for the high-score jobs to prepare for potential interviews.</li>
            </ul>
            <p><i>This is an automated report generated by your Career Pilot Agent.</i></p>
        `;

        const transporter = nodemailer.createTransport({
            service: 'gmail',
            auth: {
                user: process.env.EMAIL_USER,
                pass: process.env.EMAIL_PASS,
            },
        });

        await transporter.sendMail({
            from: `"Career Pilot" <${process.env.EMAIL_USER}>`,
            to: process.env.EMAIL_USER,
            subject: `Daily Job Application Report - ${new Date().toLocaleDateString()}`,
            html: emailHtml,
        });

        console.log("Nightly report sent successfully.");
    } catch (error) {
        console.error("Failed to send nightly report:", error);
    }
}
